/**
 * サーバが「ディスクを見た順番」を表す単調増加の通し番号（観測シーケンス）。
 *
 * 何のためか: プロジェクト一覧（`/api/projects` の全置換）と SSE のステータス差分は、
 * どちらも「ある瞬間のディスク」を観測した結果だが、クライアントへ届く順番は
 * ネットワーク次第で入れ替わる。どちらが新しい観測かを**到着順から推測する**と、
 * 遅れて着地した古い一覧が新しいライブ差分を巻き戻す（＝サイドバーの「作業中」が消える）。
 * そこで観測ごとに番号を振り、クライアントは**番号という事実**で新旧を決める。
 *
 * 正しさの根拠: 番号の採番はディスク読み取りと**同じ同期ブロック**の中で行う
 * （`resolveProjectStatus` が `readStatusFile` と同じ同期実行の中で呼ぶ）。Node は
 * シングルスレッドなので、同期ブロックは他の読み取りに割り込まれない。よって
 * 番号の大小＝読み取りの前後関係になる。非同期読み取りに使うと、この保証は失われる。
 *
 * 起点に `Date.now()` を使う理由: サーバを再起動しても、開いたままのブラウザが持つ
 * 番号より必ず大きい番号から再開するため（0 起点だと再起動後の新しい観測が
 * 「古い」と誤判定され、ライブ更新が二度と反映されなくなる）。
 * 既知の限界: システム時計が大きく巻き戻った直後の再起動では、この保証が崩れる
 * （その場合の実害はライブ更新の一時的な取りこぼしのみ。次の一覧再取得で復帰する）。
 */
let seq = Date.now();

/** 次の観測シーケンスを採番する（呼ぶたびに必ず増える）。 */
export function nextObservationSeq(): number {
  seq += 1;
  return seq;
}
